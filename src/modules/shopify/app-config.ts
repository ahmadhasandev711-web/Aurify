// Generates shopify.app.<slug>.toml for one client's Custom App (D-14).
// All subscriptions are app-specific (in the toml), because compliance topics cannot be
// subscribed through the Admin API. Deploy with: shopify app deploy --config <slug>

export const SHOPIFY_API_VERSION = '2026-10';

export const SCOPES = [
  'read_orders',
  'write_orders',
  'write_order_edits',
  'read_products',
  'read_inventory',
  'write_inventory',
  'read_locations',
  'read_merchant_managed_fulfillment_orders',
  'write_merchant_managed_fulfillment_orders',
  'read_returns',
  'write_returns',
] as const;

export const WEBHOOK_TOPICS = [
  'orders/create',
  'orders/updated',
  'orders/cancelled',
  'orders/edited',
  'fulfillment_orders/order_routing_complete',
  'fulfillment_orders/moved',
  'fulfillment_orders/cancelled',
  'fulfillment_orders/placed_on_hold',
  'fulfillment_orders/hold_released',
  'inventory_levels/update',
  'products/update',
  'products/delete',
  'locations/create',
  'locations/update',
  'locations/delete',
  'app/uninstalled',
] as const;

export const COMPLIANCE_TOPICS = ['customers/data_request', 'customers/redact', 'shop/redact'] as const;

export const WEBHOOK_PATH = '/api/webhooks/shopify';
export const OAUTH_CALLBACK_PATH = '/api/shopify/callback';

export interface AppConfigInput {
  slug: string;
  clientId: string;
  name: string;
  /** Public https URL of the Aurify web app, no trailing path. */
  appUrl: string;
}

export class AppConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'AppConfigError';
  }
}

const q = (s: string) => JSON.stringify(s); // TOML basic strings use the same escapes as JSON
const list = (xs: readonly string[], indent = '  ') => `[\n${xs.map((x) => `${indent}${q(x)},`).join('\n')}\n]`;

export function validateAppConfigInput(i: AppConfigInput): void {
  if (!/^[a-z0-9][a-z0-9-]{1,40}$/.test(i.slug)) throw new AppConfigError('slug must be lowercase letters, digits and dashes');
  if (!i.clientId.trim()) throw new AppConfigError('clientId is required');
  if (!i.name.trim()) throw new AppConfigError('name is required');
  let url: URL;
  try {
    url = new URL(i.appUrl);
  } catch {
    throw new AppConfigError('appUrl must be a valid URL');
  }
  if (url.protocol !== 'https:') throw new AppConfigError('appUrl must be https');
  if (url.pathname !== '/' || url.search || url.hash) throw new AppConfigError('appUrl must not include a path');
}

export function renderAppConfig(i: AppConfigInput): string {
  validateAppConfigInput(i);
  const base = new URL(i.appUrl).origin;
  return `# Generated by scripts/generate-app-config.ts — do not edit by hand.
# Deploy: shopify app deploy --config ${i.slug}

client_id = ${q(i.clientId)}
name = ${q(i.name)}
application_url = ${q(base + '/')}
embedded = false

[access_scopes]
scopes = ${q(SCOPES.join(','))}

[auth]
redirect_urls = [ ${q(base + OAUTH_CALLBACK_PATH)} ]

[webhooks]
api_version = ${q(SHOPIFY_API_VERSION)}

  [[webhooks.subscriptions]]
  topics = ${list(WEBHOOK_TOPICS, '    ')}
  uri = ${q(WEBHOOK_PATH)}

  [[webhooks.subscriptions]]
  compliance_topics = ${list(COMPLIANCE_TOPICS, '    ')}
  uri = ${q(WEBHOOK_PATH)}
`;
}
